import json
import os
from compat import QtWidgets, QtCore, QtGui, Qt
from secret_store import load_json_file
from orchestrator.licensing import LicenseManager, BUY_URL
from orchestrator.providers import _provider_tuning
SETTINGS_KEYS = ['retries_per_step', 'auto_replan', 'sandbox_mode', 'max_defer_attempts', 'theme', 'chat_font_size', 'code_font_size', 'temperature', 'max_history_length', 'max_tokens']
DEFAULT_SETTINGS = {'retries_per_step': 5, 'auto_replan': False, 'sandbox_mode': True, 'max_defer_attempts': 15, 'theme': 'dark', 'chat_font_size': 13, 'code_font_size': 12, 'temperature': 0.7, 'max_history_length': 50, 'max_tokens': 16384}
def load_settings(cfg):
    return {k: cfg.get(k, DEFAULT_SETTINGS[k]) for k in SETTINGS_KEYS}
def _section(title):
    lbl = QtWidgets.QLabel(f'<b>{title}</b>')
    lbl.setStyleSheet('font-size:12px;color:#00f0ff;padding-top:8px;')
    return lbl
def show_settings_dialog(sidebar):
    d = QtWidgets.QDialog(sidebar)
    d.setWindowTitle('⚙ UCAD Assistant Settings')
    d.setMinimumWidth(520)
    _current_prov = getattr(sidebar, '_current_provider', lambda: 'deepseek')()
    _prov_tuning = _provider_tuning(_current_prov)
    _prov_default_temp = _prov_tuning['temperature']
    _prov_default_tokens = _prov_tuning['max_tokens'] or 0
    d.setStyleSheet('\n        QDialog { background:\n        QLabel { color:\n        QLineEdit, QSpinBox, QDoubleSpinBox {\n            background:\n            border-radius:6px; padding:6px 10px; font-size:12px;\n        }\n        QLineEdit:focus, QSpinBox:focus, QDoubleSpinBox:focus { border-color:\n        QCheckBox { color:\n        QCheckBox::indicator { width:16px; height:16px; border-radius:3px;\n            border:1px solid\n        QCheckBox::indicator:checked { background:\n        QComboBox {\n            background:\n            border-radius:6px; padding:4px 8px; font-size:12px;\n        }\n        QComboBox:hover { border-color:\n        QComboBox::drop-down { border:none; width:16px; }\n        QSlider::groove:horizontal { height:4px; background:\n        QSlider::handle:horizontal { background:\n            margin:-5px 0; border-radius:7px; }\n        QSlider::sub-page:horizontal { background:\n        QPushButton {\n            background:\n            border-radius:8px; padding:8px 24px; font-size:12px; font-weight:600;\n        }\n        QPushButton:hover { background:\n    ')
    l = QtWidgets.QVBoxLayout(d)
    l.setSpacing(6)
    title = QtWidgets.QLabel('<b>⚙ Settings</b>')
    title.setStyleSheet('font-size:14px;color:#e6edf3;')
    l.addWidget(title)
    p = os.path.join(os.path.dirname(__file__), 'config.json')
    cfg = load_json_file(p)
    s = {}
    for k in SETTINGS_KEYS:
        v = cfg.get(k)
        s[k] = v if v is not None else DEFAULT_SETTINGS[k]
    l.addWidget(_section('🔄 Behavior'))
    r1 = QtWidgets.QHBoxLayout()
    r1.setSpacing(8)
    retry_spin = QtWidgets.QSpinBox()
    retry_spin.setRange(1, 20)
    retry_spin.setValue(int(s['retries_per_step']))
    retry_spin.setFixedWidth(80)
    r1.addWidget(QtWidgets.QLabel('Retries per step:'))
    r1.addWidget(retry_spin)
    r1.addWidget(QtWidgets.QLabel('(how many times AI retries on error)'))
    r1.addStretch()
    l.addLayout(r1)
    auto_replan_cb = QtWidgets.QCheckBox('Auto-replan on persistent failure')
    auto_replan_cb.setChecked(bool(s['auto_replan']))
    l.addWidget(auto_replan_cb)
    sandbox_cb = QtWidgets.QCheckBox('Sandbox mode (run code in subprocess)')
    sandbox_cb.setChecked(bool(s['sandbox_mode']))
    l.addWidget(sandbox_cb)
    r2 = QtWidgets.QHBoxLayout()
    r2.setSpacing(8)
    defer_spin = QtWidgets.QSpinBox()
    defer_spin.setRange(1, 100)
    defer_spin.setValue(int(s['max_defer_attempts']))
    defer_spin.setFixedWidth(80)
    r2.addWidget(QtWidgets.QLabel('Max defer attempts:'))
    r2.addWidget(defer_spin)
    r2.addWidget(QtWidgets.QLabel('(retry scheduling attempts)'))
    r2.addStretch()
    l.addLayout(r2)
    l.addWidget(_section('🔒 License'))
    lm = LicenseManager()
    r_lic = QtWidgets.QHBoxLayout()
    r_lic.setSpacing(8)
    lic_input = QtWidgets.QLineEdit()
    lic_input.setPlaceholderText('USYD-XXXX-XXXX-XXXX')
    existing_key = lm.get_license_key()
    if existing_key:
        lic_input.setText(existing_key[:4] + '‑' + '•' * 11 + existing_key[-4:])
        lic_input.setReadOnly(True)
    r_lic.addWidget(QtWidgets.QLabel('License key:'))
    r_lic.addWidget(lic_input, 1)
    lic_status = QtWidgets.QLabel('Checking...')
    lic_status.setStyleSheet('font-size:11px; padding:2px 0;')
    def _update_lic_status():
        cached = lm._read_cache()
        if not existing_key and (not lic_input.text().strip()):
            lic_status.setText('🔓 Unlicensed — no key set')
            lic_status.setStyleSheet('font-size:11px; color:#f0c040; padding:2px 0;')
        elif cached and cached.get('valid'):
            c = cached.get('activation_count', 0)
            m = cached.get('max_activations', 3)
            lic_status.setText(f'✅ Active — {c} of {m} machines')
            lic_status.setStyleSheet('font-size:11px; color:#40f070; padding:2px 0;')
        else:
            lic_status.setText('⚠️ Not validated — click Activate')
            lic_status.setStyleSheet('font-size:11px; color:#f07040; padding:2px 0;')
    _update_lic_status()
    def _do_activate():
        key = lic_input.text().strip()
        if not key:
            lic_status.setText('⚠️ Enter a license key first')
            lic_status.setStyleSheet('font-size:11px; color:#f07040; padding:2px 0;')
            return
        if '•' in key:
            lic_status.setText('License already set — no changes needed')
            return
        lic_status.setText('⏳ Validating...')
        lic_status.setStyleSheet('font-size:11px; color:#f0c040; padding:2px 0;')
        def _run():
            result = lm.validate(key)
            d._lic_thread_result = result
        def _done():
            result = getattr(d, '_lic_thread_result', {})
            if result.get('valid'):
                lm.set_license_key(key)
                lic_status.setText(f"✅ Active — {result.get('activation_count', 0)} of {result.get('max_activations', 3)} machines")
                lic_status.setStyleSheet('font-size:11px; color:#40f070; padding:2px 0;')
                lic_input.setText(key[:4] + '‑' + '•' * 11 + key[-4:])
                lic_input.setReadOnly(True)
            else:
                err = result.get('error', 'unknown')
                msgs = {'invalid_key': 'Invalid license key', 'expired': 'License has expired', 'max_activations_reached': f"Max activations ({result.get('max_activations', 3)}) reached", 'network_error': 'Network error — check internet', 'no_key': 'Enter a license key'}
                lic_status.setText(f'❌ {msgs.get(err, err)}')
                lic_status.setStyleSheet('font-size:11px; color:#f05050; padding:2px 0;')
        thread = threading.Thread(target=_run, daemon=True)
        thread.start()
        d._lic_thread = thread
        timer = QtCore.QTimer(d)
        timer.setSingleShot(True)
        timer.timeout.connect(lambda: _poll_thread(d, thread, _done, timer))
        timer.start(100)
    def _poll_thread(dlg, t, cb, timer):
        if t.is_alive():
            timer.start(100)
            return
        cb()
    def _do_deactivate():
        lic_status.setText('⏳ Deactivating...')
        lic_status.setStyleSheet('font-size:11px; color:#f0c040; padding:2px 0;')
        def _run():
            result = lm.deactivate()
            d._lic_deact_result = result
        def _done():
            result = getattr(d, '_lic_deact_result', {})
            if result.get('ok'):
                lm.set_license_key('')
                lic_input.clear()
                lic_input.setReadOnly(False)
                lic_status.setText('🔓 Deactivated — enter a key to reactivate')
                lic_status.setStyleSheet('font-size:11px; color:#f0c040; padding:2px 0;')
            else:
                lic_status.setText(f"❌ Deactivation failed: {result.get('error', 'unknown')}")
                lic_status.setStyleSheet('font-size:11px; color:#f05050; padding:2px 0;')
        thread = threading.Thread(target=_run, daemon=True)
        thread.start()
        timer = QtCore.QTimer(d)
        timer.setSingleShot(True)
        timer.timeout.connect(lambda: _poll_thread(d, thread, _done, timer))
        timer.start(100)
    lic_btn_activate = QtWidgets.QPushButton('Activate')
    lic_btn_activate.setFixedWidth(100)
    lic_btn_activate.clicked.connect(_do_activate)
    lic_btn_deactivate = QtWidgets.QPushButton('Deactivate')
    lic_btn_deactivate.setFixedWidth(100)
    lic_btn_deactivate.clicked.connect(_do_deactivate)
    if not existing_key:
        lic_btn_deactivate.setEnabled(False)
    lic_buy_link = QtWidgets.QLabel('<a href="#" style="color:#63a5ff;">Buy a license</a>')
    lic_buy_link.setOpenExternalLinks(False)
    lic_buy_link.linkActivated.connect(lambda: QtGui.QDesktopServices.openUrl(QtCore.QUrl(BUY_URL)))
    r_lic_btns = QtWidgets.QHBoxLayout()
    r_lic_btns.setSpacing(8)
    r_lic_btns.addWidget(lic_btn_activate)
    r_lic_btns.addWidget(lic_btn_deactivate)
    r_lic_btns.addWidget(lic_buy_link)
    r_lic_btns.addStretch()
    l.addLayout(r_lic)
    l.addWidget(lic_status)
    l.addLayout(r_lic_btns)
    l.addWidget(_section('🎨 Appearance'))
    r5 = QtWidgets.QHBoxLayout()
    r5.setSpacing(8)
    theme_combo = QtWidgets.QComboBox()
    theme_combo.addItem('Dark Glass', 'dark')
    theme_combo.addItem('Light', 'light')
    idx = theme_combo.findData(s.get('theme', 'dark'))
    theme_combo.setCurrentIndex(idx if idx >= 0 else 0)
    r5.addWidget(QtWidgets.QLabel('Theme:'))
    r5.addWidget(theme_combo)
    r5.addStretch()
    l.addLayout(r5)
    r6 = QtWidgets.QHBoxLayout()
    r6.setSpacing(8)
    chat_font_spin = QtWidgets.QSpinBox()
    chat_font_spin.setRange(8, 24)
    chat_font_spin.setValue(int(s['chat_font_size']))
    chat_font_spin.setFixedWidth(70)
    r6.addWidget(QtWidgets.QLabel('Chat font size:'))
    r6.addWidget(chat_font_spin)
    r6.addStretch()
    l.addLayout(r6)
    r7 = QtWidgets.QHBoxLayout()
    r7.setSpacing(8)
    code_font_spin = QtWidgets.QSpinBox()
    code_font_spin.setRange(8, 24)
    code_font_spin.setValue(int(s['code_font_size']))
    code_font_spin.setFixedWidth(70)
    r7.addWidget(QtWidgets.QLabel('Code font size:'))
    r7.addWidget(code_font_spin)
    r7.addStretch()
    l.addLayout(r7)
    l.addWidget(_section('🧪 Advanced'))
    temp_hint = QtWidgets.QLabel(f'(Provider default: {_prov_default_temp:.1f})')
    temp_hint.setStyleSheet('font-size:10px; color:#888;')
    r8 = QtWidgets.QHBoxLayout()
    r8.setSpacing(8)
    temp_slider = QtWidgets.QSlider(Qt.Horizontal)
    temp_slider.setRange(0, 200)
    temp_slider.setValue(int(float(s['temperature']) * 100))
    temp_label = QtWidgets.QLabel(f"{float(s['temperature']):.1f}")
    temp_label.setFixedWidth(30)
    temp_slider.valueChanged.connect(lambda v: temp_label.setText(f'{v / 100:.1f}'))
    r8.addWidget(QtWidgets.QLabel('AI Temperature:'))
    r8.addWidget(temp_slider, 1)
    r8.addWidget(temp_label)
    r8.addWidget(temp_hint)
    l.addLayout(r8)
    r9 = QtWidgets.QHBoxLayout()
    r9.setSpacing(8)
    history_spin = QtWidgets.QSpinBox()
    history_spin.setRange(0, 500)
    history_spin.setValue(int(s['max_history_length']))
    history_spin.setFixedWidth(80)
    r9.addWidget(QtWidgets.QLabel('Max chat history:'))
    r9.addWidget(history_spin)
    r9.addWidget(QtWidgets.QLabel('messages (0 = unlimited)'))
    r9.addStretch()
    l.addLayout(r9)
    r10 = QtWidgets.QHBoxLayout()
    r10.setSpacing(8)
    tokens_hint = QtWidgets.QLabel(f'(Provider default: {_prov_default_tokens:,})' if _prov_default_tokens else '(Provider default: none)')
    tokens_hint.setStyleSheet('font-size:10px; color:#888;')
    tokens_spin = QtWidgets.QSpinBox()
    tokens_spin.setRange(0, 131072)
    tokens_spin.setSingleStep(1024)
    tokens_spin.setValue(int(s.get('max_tokens', _prov_default_tokens or 16384)))
    tokens_spin.setFixedWidth(100)
    r10.addWidget(QtWidgets.QLabel('Max output tokens:'))
    r10.addWidget(tokens_spin)
    r10.addWidget(QtWidgets.QLabel('(0 = no cap)'))
    r10.addWidget(tokens_hint)
    r10.addStretch()
    l.addLayout(r10)
    l.addStretch()
    btns = QtWidgets.QDialogButtonBox(QtWidgets.QDialogButtonBox.Ok | QtWidgets.QDialogButtonBox.Cancel)
    def _accept():
        s['retries_per_step'] = retry_spin.value()
        s['auto_replan'] = auto_replan_cb.isChecked()
        s['sandbox_mode'] = sandbox_cb.isChecked()
        s['max_defer_attempts'] = defer_spin.value()
        s['theme'] = theme_combo.currentData() or 'dark'
        s['chat_font_size'] = chat_font_spin.value()
        s['code_font_size'] = code_font_spin.value()
        s['temperature'] = temp_slider.value() / 100
        s['max_history_length'] = history_spin.value()
        s['max_tokens'] = tokens_spin.value()
        sidebar._apply_settings(s)
        d.accept()
    btns.accepted.connect(_accept)
    btns.rejected.connect(d.reject)
    l.addWidget(btns)
    d.exec()
